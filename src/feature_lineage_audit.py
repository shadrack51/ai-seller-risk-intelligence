# ============================================================
# VALIDATION
# ============================================================

def validate_feature_definitions():

    missing_definitions = [
        feature
        for feature in MODEL_FEATURES
        if feature not in FEATURE_LINEAGE
    ]

    if missing_definitions:

        raise ValueError(
            "Missing feature lineage definitions:\n"
            + "\n".join(missing_definitions)
        )

    extra_definitions = [
        feature
        for feature in FEATURE_LINEAGE
        if feature not in MODEL_FEATURES
    ]

    if extra_definitions:

        raise ValueError(
            "Feature definitions contain unexpected features:\n"
            + "\n".join(extra_definitions)
        )


# ============================================================
# MAIN
# ============================================================

def main():

    print("=" * 70)
    print("FEATURE LINEAGE AND LEAKAGE AUDIT")
    print("=" * 70)

    # --------------------------------------------------------
    # Validate definitions
    # --------------------------------------------------------

    print("\nValidating feature definitions...")

    validate_feature_definitions()

    print("Feature lineage definitions -> PASS")

    # --------------------------------------------------------
    # Load ML dataset
    # --------------------------------------------------------

    print("\nLoading ML dataset...")

    if not ML_DATASET_PATH.exists():

        raise FileNotFoundError(
            f"ML dataset not found:\n{ML_DATASET_PATH}"
        )

    df = pd.read_csv(
        ML_DATASET_PATH
    )

    print(
        f"Rows: {len(df):,}"
    )

    print(
        f"Columns: {len(df.columns):,}"
    )

    # --------------------------------------------------------
    # Build audit table
    # --------------------------------------------------------

    audit_rows = []

    for feature in MODEL_FEATURES:

        metadata = FEATURE_LINEAGE[
            feature
        ]

        audit_rows.append(
            {
                "feature": feature,
                "source": metadata["source"],
                "type": metadata["type"],
                "target_relationship": (
                    metadata["target_relationship"]
                ),
                "production_candidate": (
                    metadata["production_candidate"]
                ),
                "reason": metadata["reason"],
            }
        )

    audit_df = pd.DataFrame(
        audit_rows
    )

    # --------------------------------------------------------
    # Display audit
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("FEATURE LINEAGE AUDIT")
    print("=" * 70)

    print(
        audit_df.to_string(
            index=False
        )
    )

    # --------------------------------------------------------
    # Feature status summary
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("FEATURE STATUS SUMMARY")
    print("=" * 70)

    status_summary = (
        audit_df["production_candidate"]
        .value_counts()
        .rename_axis("status")
        .reset_index(
            name="feature_count"
        )
    )

    print(
        status_summary.to_string(
            index=False
        )
    )

    # --------------------------------------------------------
    # Potential leakage features
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("POTENTIAL LEAKAGE FEATURES")
    print("=" * 70)

    potential_leakage = audit_df[
        audit_df["production_candidate"]
        == "NO"
    ]

    if potential_leakage.empty:

        print(
            "No features classified as definite "
            "potential leakage."
        )

    else:

        print(
            potential_leakage[
                [
                    "feature",
                    "source",
                    "target_relationship",
                    "reason",
                ]
            ].to_string(
                index=False
            )
        )

    # --------------------------------------------------------
    # Features requiring review
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("FEATURES REQUIRING REVIEW")
    print("=" * 70)

    review_features = audit_df[
        audit_df["production_candidate"]
        == "REVIEW"
    ]

    if review_features.empty:

        print(
            "No features require additional review."
        )

    else:

        print(
            review_features[
                [
                    "feature",
                    "source",
                    "target_relationship",
                    "reason",
                ]
            ].to_string(
                index=False
            )
        )

    # --------------------------------------------------------
    # Candidate production features
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("PRODUCTION CANDIDATE FEATURES")
    print("=" * 70)

    production_features = audit_df[
        audit_df["production_candidate"]
        == "YES"
    ]["feature"].tolist()

    for feature in production_features:

        print(
            f" - {feature}"
        )

    print(
        f"\nProduction candidate count: "
        f"{len(production_features)}"
    )

    # --------------------------------------------------------
    # Build production feature dataset
    # --------------------------------------------------------

    production_feature_df = pd.DataFrame(
        {
            "feature": production_features
        }
    )

    production_feature_df[
        "position"
    ] = (
        range(
            1,
            len(production_features) + 1
        )
    )

    # --------------------------------------------------------
    # Save audit
    # --------------------------------------------------------

    audit_df.to_csv(
        OUTPUT_PATH,
        index=False
    )

    production_feature_df.to_csv(
        PRODUCTION_FEATURES_PATH,
        index=False
    )

    # --------------------------------------------------------
    # Final summary
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("AUDIT SUMMARY")
    print("=" * 70)

    print(
        f"Total model features: "
        f"{len(MODEL_FEATURES)}"
    )

    print(
        f"Safe production candidates: "
        f"{len(production_features)}"
    )

    print(
        f"Features requiring review: "
        f"{len(review_features)}"
    )

    print(
        f"Potential leakage / remove: "
        f"{len(potential_leakage)}"
    )

    print(
        "\nFeature lineage audit saved to:"
    )

    print(
        OUTPUT_PATH
    )

    print(
        "\nProduction feature list saved to:"
    )

    print(
        PRODUCTION_FEATURES_PATH
    )

    print("\n" + "=" * 70)
    print("FEATURE LINEAGE AUDIT COMPLETE")
    print("=" * 70)


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()